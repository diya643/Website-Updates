# ---------------------------------------------------------------- build
def main():
    only = None
    if "--only" in sys.argv:
        only = set(sys.argv[sys.argv.index("--only") + 1].split(","))
    if only is None:
        if OUT.exists():
            shutil.rmtree(OUT)
        shutil.copytree(STATIC, OUT)
    else:
        shutil.copytree(STATIC, OUT, dirs_exist_ok=True)
    (OUT / "assets/favicon.svg").write_text(FAVICON)
    try:
        from PIL import Image
        Image.open(STATIC / "assets/pascal-logo-light.png")  # ensure PIL works
        from PIL import ImageDraw
        icon = Image.new("RGB", (180, 180), "#052A2E")
        dr = ImageDraw.Draw(icon)
        dr.rectangle((62, 36, 122, 136), outline="#E8F1EE", width=7)
        dr.rectangle((74, 48, 112, 112), fill="#55C390")
        icon.save(OUT / "assets/apple-touch-icon.png")
    except Exception:
        pass

    sources = [parse_source(fp) for fp in sorted(PAGES.glob("*.html"))]
    built_paths = {m["path"] for m, _ in sources}
    valid = built_paths | set(LIVE_PATHS) | {DEMO_URL} | {r[0] for r in REDIRECTS}
    if only is not None:
        valid |= set(SITE_PAGES)
        sources = [(m, b) for m, b in sources if m["_src"] in only or m["_src"].removesuffix(".html") in only]
    nav = expand(render_partial("nav", {}))
    footer = render_partial("footer", {})
    report = [f"# Build report — {UPDATED}\n", f"{len(sources)} pages built to `public/`.\n"]
    sitemap, llms, lastmod = [], [], {}
    total_issues = 0

    for meta, body in sources:
        body = expand(body)

        # planned links → plain blocks until the target page exists
        def planned(m):
            attrs, inner = m.group(1), m.group(2)
            href = re.search(r'href="([^"]+)"', attrs).group(1)
            if href in built_paths:
                return f"<a{attrs.replace(' data-planned', '')}>{inner}</a>"
            attrs = re.sub(r'\s*href="[^"]+"', "", attrs).replace(" data-planned", f' data-planned="{href}"')
            return f"<div{attrs}>{inner}</div>"
        body = re.sub(r"<a((?:(?!>).)*?\sdata-planned(?:(?!>).)*)>(.*?)</a>", planned, body, flags=re.S)

        body = body.replace("{{crumbs}}", breadcrumbs_html(meta.get("crumbs", [])))
        body = body.replace("{{updated}}", f'<time datetime="{meta["_updated"]}">{date.fromisoformat(meta["_updated"]).strftime("%-d %B %Y")}</time>')
        placeholders = [strip_tags(m)[:60] or "(empty)" for m in
                        re.findall(r"<[^>]*data-placeholder[^>]*>(.*?)</", body, flags=re.S)]
        noindex = bool(placeholders) or meta.get("noindex", False)
        faqs = faqs_from(body)
        page = f"""<!doctype html>
<html lang="en">
<head>
{head_html(meta, faqs, noindex)}
</head>
<body>
{nav}
<main id="main">
{body.strip()}
</main>
{footer}
</body>
</html>
"""
        page = page.replace("{{demo_url}}", DEMO_URL)
        page = re.sub(r"\{\{icon:([\w-]+)(?::([\w-]+))?\}\}", lambda m: svg(m.group(1), m.group(2) or ""), page)
        page = re.sub(r"\{\{logo:([\w-]+)(?::([\w-]+))?\}\}", lambda m: logo(m.group(1), m.group(2) or ""), page)
        left = re.findall(r"\{\{[^}]+\}\}", page)
        if left:
            raise SystemExit(f"{meta['_src']}: unresolved tokens {set(left)}")

        dest = OUT / meta["path"].strip("/") / "index.html"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(versioned(page), encoding="utf-8")
        make_og(meta, OUT / "assets/og" / f"{og_slug(meta)}.png")

        issues, warns = audit(meta, page, body, valid, noindex, placeholders)
        total_issues += len(issues)
        status = "FAIL" if issues else ("WARN" if warns else "PASS")
        report.append(f"\n## {status} · `{meta['path']}` ({meta['_src']})\n")
        report.append(f"- title ({len(meta['title'])}): {meta['title']}\n- description ({len(meta['description'])}): {meta['description']}\n- FAQs in schema: {len(faqs)} · robots: {'noindex' if noindex else 'index'}\n")
        report += [f"- ❌ {i}\n" for i in issues] + [f"- ⚠️ {w}\n" for w in warns]
        if not noindex:
            sitemap.append((meta["path"], meta.get("priority", 0.8)))
            lastmod[meta["path"]] = meta["_updated"]
        llms.append((meta, noindex))

    if only is not None:
        print("".join(report))
        print(f"\n{total_issues} blocking issue(s) in --only build (sitemap/llms.txt not regenerated).")
        return 1 if total_issues else 0

    # sitemap: live pages + new pages
    rows = [(p, 1.0 if p == "/" else 0.6) for p in LIVE_PATHS if p not in {q for q, _ in sitemap}] + sitemap
    xml = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for p, pr in rows:
        lm = f"<lastmod>{lastmod[p]}</lastmod>" if p in lastmod else ""  # live Next.js pages: no date we can vouch for
        xml.append(f"  <url><loc>{url(p)}</loc>{lm}<priority>{pr:.1f}</priority></url>")
    xml.append("</urlset>")
    (OUT / "sitemap.xml").write_text("\n".join(xml) + "\n")

    bots = ["GPTBot", "OAI-SearchBot", "ChatGPT-User", "ClaudeBot", "Claude-SearchBot", "Claude-User",
            "PerplexityBot", "Perplexity-User", "Google-Extended", "Applebot-Extended", "Bingbot", "CCBot"]
    robots = ["User-agent: *", "Allow: /", ""] + [f"User-agent: {b}\nAllow: /\n" for b in bots]
    robots.append(f"Sitemap: {SITE}/sitemap.xml")
    (OUT / "robots.txt").write_text("\n".join(robots) + "\n")

    groups = {"Home": [], "Platform": [], "Ask Pascal": [], "Pascal Agents": [], "Industries": [],
              "Founder's notes": [], "Pascal Academy": [], "Company": []}
    def short(t, n=300):
        return t if len(t) <= n else t[:n].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    for meta, noidx in llms:
        if noidx:
            continue
        p = meta["path"]
        g = ("Home" if p == "/" else "Company" if p == "/security" else
             "Industries" if p.startswith("/solutions") else
             "Founder's notes" if p.startswith("/news") else
             "Pascal Academy" if p.startswith(("/pascal-academy", "/guides")) else
             "Ask Pascal" if p.startswith("/ask-pascal") else
             "Pascal Agents" if p.startswith("/pascal-agents") else "Platform")
        groups[g].append((p.count("/"), p, f"- [{meta['title'].split(' | ')[0]}]({url(p)}): {short(meta.get('llms', meta['description']))}"))
    txt = ["# Pascal AI", "",
           "> Pascal AI Labs builds context-driven AI for institutional finance: hedge funds, asset and wealth managers, "
           "banks and financial institutions, asset servicers, private equity and private credit firms, and corporate treasury teams. "
           "Pascal grounds every answer in a firm's own context (its documents, data, decisions and permissions), cites every claim "
           "to the page, and runs agentic workflows that deliver finished work in Excel, PowerPoint and Word.", ""]
    groups["Company"] += [(9, "/about", f"- [About]({SITE}/about)"), (9, "/news", f"- [News]({SITE}/news)")]
    for g, rows in groups.items():
        if rows:
            txt += [f"## {g}", ""] + [r for _, _, r in sorted(rows, key=lambda r: (r[0], r[1]))] + [""]
    (OUT / "llms.txt").write_text("\n".join(txt))

    vercel = {"cleanUrls": True, "trailingSlash": False,
              "redirects": [{"source": s, "destination": d, "permanent": True} for s, d in REDIRECTS],
              "headers": [{"source": "/assets/(.*)", "headers": [
                  {"key": "Cache-Control", "value": "public, max-age=31536000, immutable"}]}]}
    (OUT.parent / "vercel.json").write_text(json.dumps(vercel, indent=2) + "\n")

    # Next.js: serve the static pages at clean URLs (beforeFiles overrides existing app routes)
    rewrites = ",\n".join(f"      {{ source: '{p}', destination: '{p.rstrip('/')}/index.html' }}" for p in sorted(built_paths))
    redirects = ",\n".join(f"      {{ source: '{s}', destination: '{d}', permanent: true }}" for s, d in REDIRECTS)
    (OUT.parent / "next.config.snippet.js").write_text(f"""// Merge into the existing next.config.js / next.config.mjs of the pascalailabs.com repo.
// Generated by _build/build.py on {UPDATED}. Re-generate after adding pages.
const pascalV2 = {{
  async rewrites() {{
    return {{
      beforeFiles: [
{rewrites}
      ],
    }};
  }},
  async redirects() {{
    return [
{redirects}
    ];
  }},
  async headers() {{
    return [{{ source: '/assets/:path*', headers: [{{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }}] }}];
  }},
}};
module.exports = pascalV2; // or spread these into your existing config
""")

    # 404
    nf = (PARTIALS / "404.html").read_text() if (PARTIALS / "404.html").exists() else ""
    if nf:
        page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Page not found | Pascal AI</title><meta name="robots" content="noindex"><link rel="icon" href="/assets/favicon.svg" type="image/svg+xml"><link rel="stylesheet" href="/assets/site.css"><script src="/assets/site.js" defer></script></head><body>{nav}<main id="main">{nf}</main>{footer}</body></html>"""
        page = page.replace("{{demo_url}}", DEMO_URL)
        page = re.sub(r"\{\{icon:([\w-]+)(?::([\w-]+))?\}\}", lambda m: svg(m.group(1), m.group(2) or ""), page)
        (OUT / "404.html").write_text(page)

    (ROOT / "report.md").write_text("".join(report))
    print("".join(report))
    print(f"\n{total_issues} blocking issue(s).")
    return 1 if total_issues else 0


if __name__ == "__main__":
    sys.exit(main())
