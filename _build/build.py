def make_og(meta, dest):
    try:
        from PIL import Image, ImageDraw, ImageFont, ImageFilter
    except ImportError:
        return False
    W, H = 1200, 630
    img = Image.new("RGB", (W, H), "#052A2E")
    glow = Image.new("RGB", (W, H), "#052A2E")
    gd = ImageDraw.Draw(glow)
    gd.ellipse((200, 380, 1300, 1000), fill="#1E8673")
    gd.ellipse((-200, -300, 500, 300), fill="#07434A")
    glow = glow.filter(ImageFilter.GaussianBlur(140))
    img = Image.blend(img, glow, 0.85)
    d = ImageDraw.Draw(img, "RGBA")
    for x in range(0, W, 60):
        d.line([(x, 0), (x, H)], fill=(141, 226, 181, 16))
    for y in range(0, H, 60):
        d.line([(0, y), (W, y)], fill=(141, 226, 181, 16))

    def font(name, size, var=None):
        f = ImageFont.truetype(str(FONTS / name), size)
        if var:
            try:
                f.set_variation_by_axes([var])
            except Exception:
                pass
        return f
    logo = Image.open(STATIC / "assets/pascal-logo-light.png").convert("RGBA")
    logo.thumbnail((210, 70))
    img.paste(logo, (80, 70), logo)
    kick = font("Sora-VF.ttf", 24, 500)
    d.rounded_rectangle((80, 200, 80 + d.textlength(meta.get("og_kicker", "Pascal AI").upper(), font=kick) + 66, 246),
                        radius=23, outline=(141, 226, 181, 90), width=2)
    d.ellipse((98, 217, 110, 229), fill="#55C390")
    d.text((120, 209), meta.get("og_kicker", "Pascal AI").upper(), font=kick, fill="#BCF0D5")
    title = meta.get("og_title") or meta["title"].split(" | ")[0]
    size = 64
    while size > 40:
        f = font("Sora-VF.ttf", size, 560)
        words, lines, cur = title.split(), [], ""
        for w in words:
            t = (cur + " " + w).strip()
            if d.textlength(t, font=f) > 1020:
                lines.append(cur); cur = w
            else:
                cur = t
        lines.append(cur)
        if len(lines) <= 3:
            break
        size -= 4
    y = 290
    for ln in lines:
        d.text((80, y), ln, font=f, fill="#FFFFFF")
        y += int(size * 1.14)
    d.text((80, H - 70), "pascalailabs.com", font=font("NunitoSans-VF.ttf", 24, 600), fill="#9DB8B1")
    dest.parent.mkdir(parents=True, exist_ok=True)
    img.save(dest, optimize=True)
    return True


