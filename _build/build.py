# ---------------------------------------------------------------- helpers
def esc(s):
    return html.escape(s, quote=True)


def strip_tags(s):
    s = re.sub(r"<svg.*?</svg>", "", s, flags=re.S)
    s = re.sub(r'<span class="cite[^"]*">.*?</span>', "", s, flags=re.S)
    s = re.sub(r"<[^>]+>", " ", s)
    return re.sub(r"\s+", " ", html.unescape(s)).strip()


def url(path):
    if path.startswith("http"):
        return path
    return SITE + ("" if path == "/" else path)


def parse_source(fp):
    raw = fp.read_text(encoding="utf-8")
    m = re.match(r"\s*<!--meta\s*(\{.*?\})\s*-->", raw, flags=re.S)
    if not m:
        raise SystemExit(f"{fp.name}: missing <!--meta {{...}} --> front matter")
    meta = json.loads(m.group(1))
    meta["_src"] = fp.name
    # per-page freshness: front-matter "updated" (YYYY-MM-DD) wins, else the source file's last edit
    meta["_updated"] = meta.get("updated") or date.fromtimestamp(fp.stat().st_mtime).isoformat()
    return meta, raw[m.end():]


def render_partial(name, params):
    text = (PARTIALS / f"{name}.html").read_text(encoding="utf-8")
    for k, v in params.items():
        text = text.replace("{{" + k + "}}", v)
    return text


def expand(body):
    def inc(m):
        name = m.group(1)
        params = dict(re.findall(r'(\w+)="(.*?)"', m.group(2) or ""))
        return expand(render_partial(name, params))
    return re.sub(r"<!--#include\s+(\w+(?:-\w+)*)(.*?)-->", inc, body, flags=re.S)


def breadcrumbs_html(crumbs):
    items = [("Home", "/")] + [tuple(c) for c in crumbs]
    parts = []
    for i, (label, href) in enumerate(items):
        if i == len(items) - 1:
            parts.append(f'<span aria-current="page">{esc(label)}</span>')
        else:
            parts.append(f'<a href="{href}">{esc(label)}</a><span aria-hidden="true">/</span>')
    return '<nav class="crumbs" aria-label="Breadcrumb">' + "".join(parts) + "</nav>"


def faqs_from(body):
    out = []
    for q, a in re.findall(
            r'<details class="faq-item"[^>]*>\s*<summary>(.*?)</summary>\s*<div class="ans">(.*?)</div>\s*</details>',
            body, flags=re.S):
        out.append((strip_tags(q), strip_tags(a)))
    return out


