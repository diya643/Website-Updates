# ---------------------------------------------------------------- cache busting
_VER = {}
def versioned(page):
    """Append ?v=<content hash> to every /assets/*.css and *.js the page loads. /assets/* is served
    immutable for a year, so without this a browser keeps an old stylesheet after a redeploy."""
    def sub(m):
        path = m.group(2)
        if path not in _VER:
            f = OUT / path.lstrip("/")
            _VER[path] = hashlib.md5(f.read_bytes()).hexdigest()[:10] if f.exists() else None
        v = _VER[path]
        return f'{m.group(1)}{path}?v={v}' if v else m.group(0)
    page = re.sub(r'((?:href|src)=")(/assets/[^"?#]+\.(?:css|js))(?=")', sub, page)
    # clips and photos are cached for a year too: version every src, poster and srcset entry
    return re.sub(r'((?:src|poster|srcset)="|, )(/assets/(?:clips|photos)/[^"?#, ]+\.(?:mp4|jpg|png|webp))(?=[" ])', sub, page)

