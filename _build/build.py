class Audit(HTMLParser):
    def __init__(self):
        super().__init__()
        self.h = []          # (level, text)
        self._hcur = None
        self._htxt = []
        self.imgs = []       # attrs
        self.links = []      # (href, text)
        self._a = None
        self._atxt = []
        self.in_main = False
        self.main_links = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if re.fullmatch(r"h[1-6]", tag):
            self._hcur, self._htxt = int(tag[1]), []
        elif tag == "img":
            self.imgs.append(a)
        elif tag == "a":
            self._a, self._atxt = a.get("href", ""), []
        elif tag == "main":
            self.in_main = True

    def handle_endtag(self, tag):
        if self._hcur and tag == f"h{self._hcur}":
            self.h.append((self._hcur, " ".join("".join(self._htxt).split())))
            self._hcur = None
        elif tag == "a" and self._a is not None:
            text = " ".join("".join(self._atxt).split())
            self.links.append((self._a, text))
            if self.in_main:
                self.main_links.append((self._a, text))
            self._a = None
        elif tag == "main":
            self.in_main = False

    def handle_data(self, data):
        if self._hcur:
            self._htxt.append(data)
        if self._a is not None:
            self._atxt.append(data)


def audit(meta, page_html, body, valid_paths, noindex, placeholders):
    issues, warns = [], []
    a = Audit()
    a.feed(page_html)
    tl, dl = len(meta["title"]), len(meta["description"])
    if tl > 60: issues.append(f"title is {tl} chars (max 60)")
    if not 120 <= dl <= 160: issues.append(f"meta description is {dl} chars (target 120-160)")
    h1s = [t for l, t in a.h if l == 1]
    if len(h1s) != 1: issues.append(f"{len(h1s)} H1 tags (need exactly 1)")
    prev = 1
    for lvl, txt in a.h:
        if lvl > prev + 1:
            issues.append(f"heading jumps h{prev}→h{lvl} at '{txt[:40]}'")
        prev = lvl
    for im in a.imgs:
        if "alt" not in im: issues.append(f"img without alt: {im.get('src')}")
        if not (im.get("width") and im.get("height")): warns.append(f"img without width/height: {im.get('src')}")
    internal = set()
    for href, text in a.links:
        if href.startswith("/") and not href.startswith("//"):
            p = href.split("#")[0].split("?")[0] or "/"
            if p.startswith("/assets/"):
                continue
            if p not in valid_paths:
                issues.append(f"broken internal link: {href}")
    for href, text in a.main_links:
        if href.startswith("/") and href != DEMO_URL:
            internal.add(href.split("#")[0])
        if text.lower() in ("learn more", "click here", "read more", "here"):
            warns.append(f"generic anchor text '{text}' → {href}")
    internal.discard(meta["path"])
    if len(internal) < 3: issues.append(f"only {len(internal)} contextual internal links in <main> (min 3)")
    faqs = faqs_from(body)
    if len(faqs) < meta.get("faq_min", 4): issues.append(f"{len(faqs)} FAQs (need 4-6 for FAQPage)")
    # answer-first summary: first <p> in main within 150 words should be substantial
    first_p = re.search(r'<p class="lead[^"]*"[^>]*>(.*?)</p>', body, flags=re.S)
    n = len(strip_tags(first_p.group(1)).split()) if first_p else 0
    if n < meta.get("lead_min", 12):
        issues.append(f"hero lead is {n} words (answer-first summary needs at least {meta.get('lead_min', 12)})")
    elif n > meta.get("lead_max", 40):
        warns.append(f"hero lead is {n} words")
    banned = ["delve", "underscore", "landscape", "robust", "game-changer", "game changer", "seamless", "unlock",
              "transformative", "groundbreaking", "cutting-edge", "revolutionize", "revolutionise", "empower", "embark",
              "synergy", "holistic", "streamline", "unpack", "deep dive", "it's important to note", "it's worth mentioning",
              "it's worth noting", "in today's world", "in the age of ai", "rapidly evolving", "moreover", "furthermore",
              "leverage", "leverages", "leveraging", "leveraged"]
    plain = strip_tags(body).lower().replace("’", "'")
    for w in banned:
        if re.search(r"\b" + re.escape(w) + r"\b", plain):
            issues.append(f"Pascal writing ban list: '{w}'")
    # banned "X, not Y" contrast construction: fail in headings, warn in copy (FAQ excluded)
    contrast = re.compile(r"(\.\s+not\b|,\s+not\b|\bnot just\b|\binstead of\b|\brather than\b)", re.I)
    for lvl, txt in a.h:
        if contrast.search(txt):
            issues.append(f"'X, not Y' construction in heading: '{txt[:60]}'")
    copy_no_faq = strip_tags(re.sub(r'<section[^>]*id="faq".*?</section>', "", body, flags=re.S))
    for m in contrast.finditer(copy_no_faq):
        warns.append(f"'X, not Y' construction in copy: '...{copy_no_faq[max(0, m.start()-40):m.end()+20]}...'")
    # word budget: enterprise pages stay short (FAQ answers excluded, they are collapsed)
    no_faq = re.sub(r'<section[^>]*id="faq".*?</section>', "", body, flags=re.S)
    no_faq = re.sub(r"<!--mock-->.*?<!--/mock-->", "", no_faq, flags=re.S)  # product visuals are UI, not copy
    words = len(strip_tags(re.sub(r"<(script|style)[\s\S]*?</\1>", "", no_faq)).split())
    limit = meta.get("word_limit", 600)
    if words > limit:
        issues.append(f"{words} words outside the FAQ (budget {limit}); cut copy")
    elif words > limit * 0.85:
        warns.append(f"{words} words outside the FAQ (budget {limit})")
    if noindex:
        warns.append(f"NOINDEX: {len(placeholders)} placeholder(s) still to fill: " + "; ".join(placeholders[:4]))
    return list(dict.fromkeys(issues)), list(dict.fromkeys(warns))


